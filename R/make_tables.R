#!/usr/bin/env Rscript
# Tables 2 to 6, from the long and detailed panels: coverage, adherence,
# adherence by era, the corridor test, shock years.

options(stringsAsFactors = FALSE)
BASE <- here::here()
OUT  <- file.path(BASE, "outputs")
dir.create(OUT, showWarnings = FALSE)

fmt  <- function(x, d = 1) formatC(x, format = "f", digits = d, big.mark = ",")
fmt0 <- function(x) formatC(x, format = "d", big.mark = ",")

CODE <- c(gdp_growth      = "NY.GDP.MKTP.KD.ZG",
          gdp_pc          = "NY.GDP.PCAP.KD",
          inflation       = "FP.CPI.TOTL.ZG",
          broad_money_gdp = "FM.LBL.BMNY.GD.ZS",
          trade_balance   = "NE.RSB.GNFS.ZS",
          unemployment    = "SL.UEM.TOTL.ZS",
          real_interest   = "FR.INR.RINR")

LAB <- c(gdp_growth      = "GDP growth (annual %)",
         gdp_pc          = "GDP per capita (constant 2015 US$)",
         inflation       = "Inflation, consumer prices (annual %)",
         broad_money_gdp = "Broad money (% of GDP)",
         trade_balance   = "External balance on goods and services (% of GDP)",
         unemployment    = "Unemployment (% of labour force)",
         real_interest   = "Real interest rate, bank lending (%)")

# T2 panel A: the long panel
lg <- read.csv(file.path(BASE, "data/wdi_long_1960_2023.csv"))
lg <- lg[order(lg$country, lg$year), ]
A_IND <- c("gdp_growth", "gdp_pc", "inflation", "broad_money_gdp",
           "trade_balance", "unemployment", "real_interest")
# the long panel builds trade_balance as exports minus imports; the 2008-2023 file
# carries the published balance. they agree exactly (checked below), one code for both
lg$trade_balance <- lg$exports_gdp - lg$imports_gdp

first30 <- function(v) {
  n <- tapply(!is.na(v), lg$year, sum)
  y <- as.integer(names(n)[n >= 30])
  if (length(y)) min(y) else NA_integer_
}

A <- do.call(rbind, lapply(A_IND, function(i) {
  v  <- lg[[i]]
  ok <- !is.na(v)
  data.frame(series = LAB[i], code = CODE[i],
             countries = length(unique(lg$country[ok])),
             obs = sum(ok),
             pct = 100 * sum(ok) / nrow(lg),
             y30 = first30(v))
}))

# T2 panel B: the detailed panel
source(file.path(BASE, "R/panel.R"))
dt     <- load_panel()                        # 217 economies, aggregates dropped
dt_raw <- load_panel(drop_aggregates = FALSE) # 225 entities, for the note below
B_IND <- c("gdp_growth", "inflation", "real_interest", "broad_money_gdp",
           "trade_balance", "unemployment")
dev_n <- sum(dt$development_status == "Developed")
tra_n <- sum(dt$development_status == "Developing")

B <- do.call(rbind, lapply(B_IND, function(i) {
  v <- dt[[i]]
  data.frame(series = LAB[i], code = CODE[i],
             obs = sum(!is.na(v)),
             pct_missing = 100 * mean(is.na(v)),
             dev = sum(!is.na(v) & dt$development_status == "Developed"),
             tra = sum(!is.na(v) & dt$development_status == "Developing"),
             n_countries_dev = length(unique(dt$country[!is.na(v) &
                                       dt$development_status == "Developed"])))
}))

ok_tb <- complete.cases(dt$trade_balance, dt$exports_goods_services, dt$imports_goods_services)
tb_max <- max(abs(dt$trade_balance[ok_tb] -
                  (dt$exports_goods_services[ok_tb] - dt$imports_goods_services[ok_tb])))
ok_em  <- complete.cases(dt$employment, dt$unemployment)
em_sum <- unique(round(dt$employment[ok_em] + dt$unemployment[ok_em], 6))
stopifnot(tb_max < 1e-8, length(em_sum) == 1, abs(em_sum - 100) < 1e-8)

extracted <- format(file.info(file.path(BASE, "data/magic_squares_data_clean.csv"))$mtime, "%Y-%m-%d")

p <- file.path(OUT, "T2_data_coverage.md")
con <- file(p, open = "wt", encoding = "UTF-8"); on.exit(close(con), add = TRUE)
w <- function(...) cat(..., "\n", sep = "", file = con)

w("<!-- generated by R/make_tables.R. Do not edit by hand. -->")
w("")
w("**Table 2. The two panels and their coverage.**")
w("")
w("*Panel A. The long panel, 1960-2023.* ", fmt0(length(unique(lg$country))),
  " economies, ", fmt0(nrow(lg)), " country-years.")
w("")
w("| Series | WDI code | Economies | Observations | Observed | Usable from |")
w("|---|---|---|---|---|---|")
for (k in seq_len(nrow(A)))
  w("| ", A$series[k], " | `", A$code[k], "` | ", fmt0(A$countries[k]), " | ",
    fmt0(A$obs[k]), " | ", fmt(A$pct[k]), "% | ",
    ifelse(is.na(A$y30[k]), "never", A$y30[k]), " |")
w("")
w("*\"Usable from\" is the first year in which at least 30 economies report the series.",
  " Unemployment and the real interest rate are why the long panel scores three corridors",
  " rather than five.*")
w("")
w("*Panel B. The detailed panel, ", min(dt$year), "-", max(dt$year), ".* ",
  fmt0(length(unique(dt$country))), " economies, ", fmt0(nrow(dt)),
  " country-years, of which ", fmt0(dev_n), " are classified developed and ",
  fmt0(tra_n), " transforming.")
w("")
w("| Series | WDI code | Observations | Missing | Developed | Transforming |")
w("|---|---|---|---|---|---|")
for (k in seq_len(nrow(B)))
  w("| ", B$series[k], " | `", B$code[k], "` | ", fmt0(B$obs[k]), " | ",
    fmt(B$pct_missing[k]), "% | ", fmt0(B$dev[k]), " | ", fmt0(B$tra[k]), " |")
w("")
w("**Notes.**")
w("")
w("*Classification.* An economy is developed if GDP per capita in constant 2015 US dollars",
  " is at or above the World Bank high-income line of $12,696, and transforming otherwise",
  ". In the detailed panel the",
  " assignment is fixed, giving ",
  length(unique(dt$country[dt$development_status == "Developed"])), " developed and ",
  length(unique(dt$country[dt$development_status == "Developing"])),
  " transforming economies. In the long panel it is applied per country-year, so an economy",
  " that crosses the line faces the corridor for its stage at the time. The corridors differ",
  " across this binary, so it is stated rather than assumed.")
w("")
w("*Excluded entities.* The source file holds ", length(unique(dt_raw$country)),
  " entities, eight of which are World Bank aggregates: `S1` Small states, `S2` Pacific",
  " island small states, `S3` Caribbean small states, `S4` Other small states, and",
  " `V1`-`V4`, the four demographic-dividend groupings. Each pools economies already counted",
  " individually in the same file, so retaining them double-counts. They are dropped,",
  " removing ", fmt0(nrow(dt_raw) - nrow(dt)), " country-years and leaving ",
  length(unique(dt$country)), " economies. The replication archive enumerates the sovereign,",
  " non-sovereign and aggregate classes separately and reports adherence under each",
  " definition; the footnote to Section 3.1 states why the non-sovereign units are kept.")
w("")
w("*The adherence sample.* Adherence is computed where both the indicator and GDP growth are",
  " observed, which is the estimation sample. Computed instead on every observation of the",
  " indicator, three of the ten cells move by up to 0.6 points: the developed trade balance",
  " reads 50.1 rather than 50.6, developed unemployment 57.9 rather than 58.5. The",
  " estimation-sample definition is the one reported throughout.")
w("")
w("*The real interest rate.* World Bank `FR.INR.RINR` is the rate banks charge on loans,",
  " deflated by the GDP deflator. It contains a credit spread and therefore exceeds the",
  " central bank's policy rate by construction. It is called the real bank lending rate",
  " throughout and is not treated as a measure of the monetary policy stance. It is the",
  " sparsest series here, missing for ", fmt(B$pct_missing[B_IND == "real_interest"]),
  "% of the detailed panel, and the developed-economy figures rest on ",
  B$n_countries_dev[B_IND == "real_interest"], " of ",
  length(unique(dt$country[dt$development_status == "Developed"])), " economies.")
w("")
w("*The trade balance.* The detailed panel carries the published external balance",
  " (`NE.RSB.GNFS.ZS`); the long panel carries exports minus imports",
  " (`NE.EXP.GNFS.ZS` less `NE.IMP.GNFS.ZS`). The two are identical in every one of the ",
  fmt0(sum(ok_tb)), " observations where both exist, to within floating-point error,",
  " so the series are treated as one.")
w("")
w("*Employment.* The `employment` column of the detailed panel is exactly 100 minus the",
  " unemployment rate, not an independently measured employment-to-population ratio. It",
  " matches the framework's own definition, which states the employment threshold as",
  " unemployment below 10 percent, but it carries no information the unemployment series",
  " does not.")
w("")
w("*Winsorising.* None. Broad money reaches ", fmt(max(dt$broad_money_gdp, na.rm = TRUE)),
  "% of GDP and inflation reaches ", fmt(max(dt$inflation, na.rm = TRUE)),
  "%. Because compliance is an indicator function on a fixed interval rather than a",
  " conditional mean, these observations affect the outside-corridor group's outcome mean",
  " but cannot move the assignment itself.")
w("")
w("*Data release and extraction date.* The long panel was drawn from the World Bank API on 2026-08-16 by",
  " the fetch script in the replication archive, which records the indicator codes. The",
  " detailed panel file is",
  " dated ", extracted, ". The WDI release it came from is not recorded, and a re-pull on",
  " 2026-08-18 does not reproduce it: 11 entities have left the non-aggregate set, and of the",
  " observations present in both, between 5 and 46 percent have been revised depending on the",
  " series; the comparison is in the replication archive. **Corridor adherence is nonetheless",
  " stable under the revision: the largest single cell moves 2.2 points and the two group means",
  " move 0.1 and 0.9. The file should be archived with the replication package and described as",
  " the January 2026 extraction, not re-pulled.**")

cat("written: outputs/T2_data_coverage.md\n")
cat("panel A:", nrow(lg), "rows,", length(unique(lg$country)), "countries\n")
cat("panel B:", nrow(dt), "rows,", length(unique(dt$country)), "countries\n")

# T3: adherence by indicator and development group, 2008-2023
# recomputed from the 217-economy panel, not the earlier 225-entity result
CORR <- list(
  Developed  = list(real_interest = c(0, 2), inflation = c(1, 3), broad_money_gdp = c(70, 120),
                    trade_balance = c(-3, 6), unemployment = c(3, 8)),
  Developing = list(real_interest = c(0, 3), inflation = c(2, 5), broad_money_gdp = c(40, 80),
                    trade_balance = c(-8, 3), unemployment = c(5, 12)))
IND5 <- names(CORR$Developed)
IL <- c(real_interest = "Real bank lending rate", inflation = "Inflation",
        broad_money_gdp = "Broad money / GDP", trade_balance = "Trade balance",
        unemployment = "Unemployment")

cell2 <- function(ind, g, b) {
  s <- dt$development_status == g & !is.na(dt[[ind]]) & !is.na(dt$gdp_growth)
  list(pct = 100 * mean(dt[[ind]][s] >= b[1] & dt[[ind]][s] < b[2]),
       n = sum(s), band = sprintf("[%g, %g)", b[1], b[2]))
}
cell <- function(ind, g) {
  b <- CORR[[g]][[ind]]
  s <- dt$development_status == g & !is.na(dt[[ind]]) & !is.na(dt$gdp_growth)
  list(pct = 100 * mean(dt[[ind]][s] >= b[1] & dt[[ind]][s] < b[2]),
       n = sum(s), band = sprintf("[%g, %g)", b[1], b[2]))
}

p3 <- file.path(OUT, "T3_adherence.md")
c3 <- file(p3, open = "wt", encoding = "UTF-8")
w3 <- function(...) cat(..., "\n", sep = "", file = c3)
w3("<!-- generated by R/make_tables.R. Do not edit by hand. -->")
w3("")
w3("**Table 3. Corridor adherence by indicator and development group, 2008-2023.**")
w3("")
w3("| Indicator | Developed corridor | Adherence | *n* | Transforming corridor | Adherence | *n* |")
w3("|---|---|---|---|---|---|---|")
md <- c(); mt <- c()
for (i in IND5) {
  a <- cell(i, "Developed"); b <- cell(i, "Developing")
  md <- c(md, a$pct); mt <- c(mt, b$pct)
  w3("| ", IL[i], " | ", a$band, " | ", fmt(a$pct), "% | ", fmt0(a$n), " | ",
     b$band, " | ", fmt(b$pct), "% | ", fmt0(b$n), " |")
}
alt <- cell2("inflation", "Developed", c(0, 2))
md_alt <- md; md_alt[IND5 == "inflation"] <- alt$pct
w3("| *Inflation, developed, on the stated 0-2% band* | *[0, 2)* | *", fmt(alt$pct),
   "%* | *", fmt0(alt$n), "* | | | |")
w3("| **Mean of the five** | | **", fmt(mean(md)), "%** | | | **", fmt(mean(mt)), "%** | |")
w3("| *Mean with inflation on [0, 2)* | | *", fmt(mean(md_alt)), "%* | | | | |")
w3("")
w3("*Developed inflation is stated by the framework as 0-2% and was scored in the original analysis as",
   " [1, 3). Both are reported: the two bands overlap on [1, 2), which holds 21.2% of developed",
   " observations, and the tails roughly cancel, so the choice moves the group mean by 0.2 points.",
   " Everything else in the paper uses the scored band.*")
w3("")
w3("*Adherence is the share of country-years in which the indicator and GDP growth are both",
   " observed and the indicator lies inside the corridor. Only the developed trade balance and",
   " unemployment corridors are met by a majority. The real bank lending rate, on which the",
   " framework is most prescriptive, is the least adhered to of the five in both groups.*")
close(c3)
# written as a csv twin so Figure 1 plots exactly what the table prints
T3 <- do.call(rbind, lapply(IND5, function(i) {
  a <- cell(i, "Developed"); b <- cell(i, "Developing")
  data.frame(indicator = i, label = IL[i],
             dev_band = a$band, dev_pct = a$pct, dev_n = a$n,
             tra_band = b$band, tra_pct = b$pct, tra_n = b$n)
}))
write.csv(T3, file.path(OUT, "T3_adherence.csv"), row.names = FALSE)
cat("written: outputs/T3_adherence.{md,csv}\n")

# T4: adherence by era, 1960-2023
era <- read.csv(file.path(BASE, "data/historical_20260816/historical_by_era.csv"))
