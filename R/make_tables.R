   " The gaps compare country-years meeting at least two of the three against those meeting at most",
   " one, on mean growth and on the standard deviation of growth over the following five years. A",
   " positive growth gap and a negative volatility gap favour the corridor. Intervals are",
   " country-cluster bootstrap intervals, 20,000 draws. The growth advantage appears in one cell of",
   " eleven, transforming economies in the 1980s; the volatility advantage appears in nine of eleven",
   " and excludes zero in three.*")
close(c4); cat("written: outputs/T4_adherence_by_era.md\n")

# T5: outcomes by side of each bound
asym <- read.csv(file.path(BASE, "data/necessity_20260816/asymmetry_by_side.csv"))
g <- function(gr, i, s, col) {
  v <- asym[asym$group == gr & asym$indicator == i & asym$side == s, col]
  if (length(v)) v else NA_real_
}
f2 <- function(x) if (is.na(x)) "--" else sprintf("%.2f", x)
f1 <- function(x) if (is.na(x)) "--" else sprintf("%.1f", x)

p5 <- file.path(OUT, "T5_corridor_test.md")
c5 <- file(p5, open = "wt", encoding = "UTF-8")
w5 <- function(...) cat(..., "\n", sep = "", file = c5)
w5("<!-- generated by R/make_tables.R. Do not edit by hand. -->")
w5("")
w5("**Table 5. Outcomes below, inside and above each bound.**")
w5("")
# one header row only: pandoc reads a second header row as data
w5("| Group | Indicator | Volatility below | inside | above | Successful below | inside | above | Corridor? |")
w5("|---|---|---|---|---|---|---|---|---|")
for (gr in c("Developed", "Developing")) for (i in IND5) {
  sdv <- sapply(c("below", "inside", "above"), function(s) g(gr, i, s, "sd_growth_5y"))
  suc <- sapply(c("below", "inside", "above"), function(s) g(gr, i, s, "pct_S2"))
  ok  <- if (all(!is.na(sdv)) && which.min(sdv) == 2) "**yes**" else "no"
  w5("| ", ifelse(gr == "Developing", "Transforming", "Developed"), " | ", IL[i], " | ",
     f2(sdv[1]), " | ", f2(sdv[2]), " | ", f2(sdv[3]), " | ",
     f1(suc[1]), " | ", f1(suc[2]), " | ", f1(suc[3]), " | ", ok, " |")
}
w5("")
w5("*Growth volatility is the mean standard deviation of GDP growth over the five-year window;",
   " successful spells are those with mean growth above the group threshold and no contracting year,",
   " as a percentage. A bound behaves as a corridor when the middle is favourable relative to both",
   " sides; the last column marks the cells where volatility is lowest inside. Where a bound fails,",
   " it fails at the floor: developed inflation and broad money are steadiest below their lower",
   " bound, transforming unemployment is monotone, and transforming broad money is least successful",
   " inside its own band.*")
close(c5); cat("written: outputs/T5_corridor_test.md\n")

# T6: the score falls in shock years, and which corridor gave way
by <- read.csv(file.path(BASE, "data/historical_20260816/adherence_by_year_by_indicator.csv"))
top <- head(by[order(by$d_score), ], 10)
top <- top[order(top$year), ]
EVENT <- c("1965" = "", "1973" = "first oil embargo", "1974" = "first oil shock",
           "1979" = "second oil shock", "1980" = "Volcker disinflation begins",
           "1985" = "", "1991" = "", "2008" = "global financial crisis and commodity spike",
           "2019" = "", "2022" = "global inflation surge")

p6 <- file.path(OUT, "T6_shock_years.md")
c6 <- file(p6, open = "wt", encoding = "UTF-8")
w6 <- function(...) cat(..., "\n", sep = "", file = c6)
w6("<!-- generated by R/make_tables.R. Do not edit by hand. -->")
w6("")
w6("**Table 6. The ten largest annual falls in adherence, 1960-2023.**")
w6("")
w6("| Year | Score | Change | Inflation | Broad money | Trade balance | Economies | |")
w6("|---|---|---|---|---|---|---|---|")
for (k in seq_len(nrow(top)))
  w6("| ", top$year[k], " | ", sprintf("%.2f", top$score[k]), " | ",
     sprintf("%+.2f", top$d_score[k]), " | ", sprintf("%+.1f", top$d_inflation[k]), " | ",
     sprintf("%+.1f", top$d_broad_money_gdp[k]), " | ", sprintf("%+.1f", top$d_trade_balance[k]),
     " | ", top$n[k], " | ", EVENT[as.character(top$year[k])], " |")
w6("")
w6("*Change is the year-on-year movement in the mean number of corridors met; the three indicator",
   " columns are the change in the percentage of economies inside each corridor, in points, and they",
   " attribute the fall. Two kinds of event appear. In 2008 and 2022 the fall is almost entirely the",
   " inflation corridor (-24.0 and -26.6 points) with the other two nearly still. In 1974 it is almost",
   " entirely the trade balance (-32.2) with inflation barely moving. The oil shock arrived through the",
   " external balance; the other two arrived through prices.*")
w6("")
w6("*What the index does not detect is as informative. In 2020, the largest global output contraction",
   " since the Second World War, the score moved from 1.27 to 1.26. None of the three corridors scored",
   " over this period is on GDP growth, which is the outcome variable, so a pure output shock leaves the",
   " index untouched. The diagnostic is sensitive to price and external disturbance and blind to",
   " output.*")
close(c6); cat("written: outputs/T6_shock_years.md\n")
