  w4("| ", era$era[k], " | ", ifelse(era$status[k] == "Developing", "Transforming", "Developed"),
     " | ", era$n_countries[k], " | ", fmt0(era$n[k]), " | ", fmt(era$pct_adherent_all3[k]), "% | ",
     sprintf("%.2f", era$mean_K[k]), " | ", sprintf("%+.2f", era$growth_gap[k]), " | ",
     ci(era$growth_gap_lo[k], era$growth_gap_hi[k]), " | ",
     sprintf("%+.2f", era$sd_gap[k]), " | ", ci(era$sd_gap_lo[k], era$sd_gap_hi[k]), " |")
